"""Generate the flash-resident UI from the same source used by the console."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "web/index.html"
DEST = ROOT / "firmware/esp32_cam_final/web_ui.h"


def render():
    html = SOURCE.read_text(encoding="utf-8").replace('data-backend="hub"', 'data-backend="device"')
    assert ')CAMUI"' not in html
    return '// Generated by tools/embed_web.py; edit web/index.html instead.\n#pragma once\nstatic const char INDEX_HTML[] PROGMEM = R"CAMUI(' + html + ')CAMUI";\n'


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not DEST.exists() or DEST.read_text(encoding="utf-8") != content:
            raise SystemExit("web_ui.h is out of date; run tools/embed_web.py")
        print("embedded UI matches web/index.html")
    else:
        DEST.write_text(content, encoding="utf-8")
        print("generated firmware/esp32_cam_final/web_ui.h")
